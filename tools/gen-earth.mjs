// Rasterises Natural Earth (public domain) land, lakes and glaciers into a 2-bit class map and
// writes it run-length encoded to src/data/earth.js.
//   node tools/gen-earth.mjs <dir with ne_50m_land/lakes/glaciated .geojson>
// Classes: 0 ocean, 1 land, 2 ice, 3 lake.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2] || '.';
const W = 1024, H = 512;
const map = new Uint8Array(W * H);

function polygons(file) {
  const fc = JSON.parse(readFileSync(join(dir, file), 'utf8'));
  const out = [];
  for (const f of fc.features) {
    const g = f.geometry;
    if (!g) continue;
    if (g.type === 'Polygon') out.push(g.coordinates);
    else if (g.type === 'MultiPolygon') for (const p of g.coordinates) out.push(p);
  }
  return out;
}

// Even-odd scanline fill of one polygon (outer ring plus holes) with class `cls`.
function fill(poly, cls) {
  const edges = [];
  for (const ring of poly) {
    for (let i = 0; i < ring.length - 1; i++) edges.push([ring[i][0], ring[i][1], ring[i + 1][0], ring[i + 1][1]]);
  }
  let ymin = 90, ymax = -90;
  for (const e of edges) { ymin = Math.min(ymin, e[1], e[3]); ymax = Math.max(ymax, e[1], e[3]); }
  const r0 = Math.max(0, Math.floor((90 - ymax) / 180 * H)), r1 = Math.min(H - 1, Math.ceil((90 - ymin) / 180 * H));
  for (let y = r0; y <= r1; y++) {
    const lat = 90 - ((y + 0.5) * 180) / H;
    const xs = [];
    for (const [x0, y0, x1, y1] of edges) {
      if ((y0 <= lat && y1 > lat) || (y1 <= lat && y0 > lat)) xs.push(x0 + ((lat - y0) / (y1 - y0)) * (x1 - x0));
    }
    xs.sort((a, b) => a - b);
    for (let k = 0; k + 1 < xs.length; k += 2) {
      const c0 = Math.max(0, Math.round(((xs[k] + 180) / 360) * W)), c1 = Math.min(W, Math.round(((xs[k + 1] + 180) / 360) * W));
      for (let x = c0; x < c1; x++) map[y * W + x] = cls;
    }
  }
}

for (const p of polygons('ne_50m_land.geojson')) fill(p, 1);
for (const p of polygons('ne_50m_lakes.geojson')) fill(p, 3);
for (const p of polygons('ne_50m_glaciated.geojson')) fill(p, 2);
// The glacier layer leaves the Antarctic ice shelves out of the land layer's coast; treat everything
// south of 60S that is land as ice too.
for (let y = 0; y < H; y++) {
  const lat = 90 - ((y + 0.5) * 180) / H;
  if (lat < -60) for (let x = 0; x < W; x++) if (map[y * W + x] === 1) map[y * W + x] = 2;
}

// Run-length encode: byte = cls << 6 | (len - 1), runs of at most 64, row by row.
const bytes = [];
for (let y = 0; y < H; y++) {
  let x = 0;
  while (x < W) {
    const c = map[y * W + x];
    let n = 1;
    while (x + n < W && n < 64 && map[y * W + x + n] === c) n++;
    bytes.push((c << 6) | (n - 1));
    x += n;
  }
}
const b64 = Buffer.from(bytes).toString('base64');
mkdirSync('src/data', { recursive: true });
writeFileSync('src/data/earth.js', `// Generated by tools/gen-earth.mjs from Natural Earth 1:50m land, lakes and glaciers (public domain).\n// ${W}x${H} equirectangular, west to east from 180W, north to south. Classes: 0 ocean, 1 land, 2 ice, 3 lake.\nexport const EARTH_W = ${W}, EARTH_H = ${H};\nexport const EARTH_RLE = '${b64}';\n`);
writeFileSync(join(dir, 'earth.pgm'), Buffer.concat([Buffer.from(`P5 ${W} ${H} 255\n`), Buffer.from(map.map((c) => [10, 120, 255, 60][c]))]));
console.log(`earth: ${bytes.length} bytes RLE, ${b64.length} base64`);

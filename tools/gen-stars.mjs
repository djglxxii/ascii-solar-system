// Packs the Yale Bright Star Catalogue (5th ed.) down to the naked-eye stars and writes
// src/data/stars.js.   node tools/gen-stars.mjs <path to bsc5-short.json>
// Per star, 6 bytes: RA (uint16, 0..360 deg), Dec (uint16, -90..90 deg), V magnitude
// ((V + 2) * 25, uint8), temperature / 100 K (uint8).

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const src = JSON.parse(readFileSync(process.argv[2] || 'bsc5-short.json', 'utf8'));
const MAX_V = 6.2;
const out = [];
const named = [];
for (const s of src) {
  const V = parseFloat(s.V);
  if (!(V <= MAX_V)) continue;
  const ra = s.RA.match(/(\d+)h\s*(\d+)m\s*([\d.]+)s/);
  const de = s.Dec.match(/([+-])(\d+)°\s*(\d+)′\s*([\d.]+)″/);
  if (!ra || !de) continue;
  const raDeg = (+ra[1] + +ra[2] / 60 + +ra[3] / 3600) * 15;
  const decDeg = (de[1] === '-' ? -1 : 1) * (+de[2] + +de[3] / 60 + +de[4] / 3600);
  const K = parseFloat(s.K) || 5800;
  out.push([raDeg, decDeg, V, K]);
  if (s.N && V < 1.6) named.push([s.N, out.length - 1]);
}
out.sort((a, b) => a[2] - b[2]);
const buf = Buffer.alloc(out.length * 6);
out.forEach(([ra, dec, V, K], i) => {
  buf.writeUInt16LE(Math.round((ra / 360) * 65535) & 65535, i * 6);
  buf.writeUInt16LE(Math.round(((dec + 90) / 180) * 65535), i * 6 + 2);
  buf.writeUInt8(Math.max(0, Math.min(255, Math.round((V + 2) * 25))), i * 6 + 4);
  buf.writeUInt8(Math.max(10, Math.min(255, Math.round(K / 100))), i * 6 + 5);
});
mkdirSync('src/data', { recursive: true });
writeFileSync('src/data/stars.js', `// Generated by tools/gen-stars.mjs from the Yale Bright Star Catalogue, 5th revised edition.\n// ${out.length} stars brighter than V ${MAX_V}, sorted bright to faint; 6 bytes each (see the tool).\nexport const STAR_COUNT = ${out.length};\nexport const STARS_B64 = '${buf.toString('base64')}';\n`);
console.log(`stars: ${out.length}, ${(buf.length / 1024).toFixed(1)} KB`);
